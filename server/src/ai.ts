/** Общее для всех моделей: интерфейс, промпты, схема ответа. Весь ввод из OSM и Википедии — данные, а не инструкции. */
import { z } from 'zod';
import type { Candidate } from './services.ts';

export interface SelectStopsInput {
  start: { lat: number; lng: number; label?: string };
  candidates: Candidate[];
  walkMeters: number;
  maxStops: number;
  maxMinutes?: number;
  roundTrip: boolean;
  interests?: string;
  lang: string;
}

export interface StopSelection {
  title: string;
  description: string;
  stops: { candidateId: string; teaser: string }[];
}

export interface StoryInput {
  name: string;
  kind?: string;
  lang: string;
  routeTitle?: string;
  source?: string;
  style?: StoryStyle;
}

export interface AI {
  selectStops(input: SelectStopsInput): Promise<StopSelection>;
  writeStory(input: StoryInput): Promise<string>;
}

const LANG_NAMES: Record<string, string> = {
  ru: 'русском',
  en: 'английском',
  de: 'немецком',
  fr: 'французском',
  es: 'испанском',
  it: 'итальянском',
};

export const SelectionSchema = z.object({
  title: z.string(),
  description: z.string(),
  stops: z.array(z.object({ candidate_id: z.string(), teaser: z.string() })),
});

